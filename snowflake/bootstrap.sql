-- One-time bootstrap, run once by an ACCOUNTADMIN in a Snowsight worksheet.
-- Creates the only things Terraform cannot create for itself: its own role and service user, and an account-wide
-- spending cap (resource monitors need ACCOUNTADMIN). Everything else lives in terraform/.
USE ROLE ACCOUNTADMIN;

-- Hard cap so a runaway warehouse can never burn the budget: notify at 75%, suspend at 90%, kill at 100%.
CREATE RESOURCE MONITOR IF NOT EXISTS FINOPS_ACCOUNT_CAP
  WITH CREDIT_QUOTA = 40 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER ACCOUNT SET RESOURCE_MONITOR = FINOPS_ACCOUNT_CAP;

CREATE ROLE IF NOT EXISTS FINOPS_ADMIN COMMENT = 'Platform role used by Terraform and the daily showback job';
GRANT CREATE WAREHOUSE, CREATE DATABASE, CREATE ROLE, CREATE USER ON ACCOUNT TO ROLE FINOPS_ADMIN;
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE FINOPS_ADMIN;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE FINOPS_ADMIN;   -- read ACCOUNT_USAGE
GRANT ROLE FINOPS_ADMIN TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS PLATFORM_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Runs the showback extract';
GRANT USAGE, OPERATE ON WAREHOUSE PLATFORM_WH TO ROLE FINOPS_ADMIN;

-- Key-pair service user: no password exists for it anywhere.
CREATE USER IF NOT EXISTS FINOPS_SVC
  TYPE = SERVICE DEFAULT_ROLE = FINOPS_ADMIN DEFAULT_WAREHOUSE = PLATFORM_WH
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE FINOPS_ADMIN TO USER FINOPS_SVC;

SELECT 'bootstrap done' AS status;
